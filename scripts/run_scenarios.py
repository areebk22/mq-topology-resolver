"""Run every estate x configuration in tests/scenarios.py and write docs/SCENARIO_RESULTS.md.

    python scripts/run_scenarios.py              # all estates except 'large'
    python scripts/run_scenarios.py --large      # include the 2,500-app estate
"""
import argparse
import pathlib
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "src"), str(ROOT / "tests")]

from mqresolver import pipeline  # noqa: E402
from mqresolver.policy import PolicyError  # noqa: E402
import scenarios  # noqa: E402

LARGE_CONFIGS = ("default", "isolate+domain-hard", "isolate-soft+domain-soft")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--large", action="store_true")
    ap.add_argument("--out", default=str(ROOT / "docs" / "SCENARIO_RESULTS.md"))
    a = ap.parse_args()
    rows, failures = [], 0
    for est, (desc, _) in scenarios.ESTATES.items():
        if est == "large" and not a.large:
            continue
        src, fname, mapping = scenarios.estate(est)
        for cname, cfg in scenarios.configs(est).items():
            if est == "large" and cname not in LARGE_CONFIGS:
                continue
            t = time.time()
            try:
                b = pipeline.run(src, filename=fname, mapping=mapping, config=cfg, include_graph=False)
            except PolicyError as exc:
                rows.append((est, cname, "infeasible", str(exc)[:90]))
                print(f"{est:15s} {cname:26s} infeasible: {exc}", flush=True)
                continue
            s, sc = b["summary"], b["score"]
            hard_ok = all(p["violating"] == 0 for p in b["policies"]["target"] if p["mode"] == "hard")
            exc = sum(len(p.get("exceptions", [])) for p in b["policies"]["target"])
            ok = b["validation"]["passed"] and sc["anchors_ok"] and hard_ok
            failures += not ok
            rows.append((est, cname, "pass" if ok else "FAIL",
                         f"{s['apps']} | {s['as_is']['queue_managers']} → {s['target']['queue_managers']} | "
                         f"{s['as_is']['channel_pairs']} → {s['target']['channel_pairs']} | "
                         f"{s['target']['same_qm_flow_pct']}% | {sc['as_is']['tci']} → {sc['target']['tci']} "
                         f"({sc['change_pct']}%) | {time.time() - t:.1f}s"
                         + (f" | {exc} single-app QM(s) over the queue limit (unavoidable)" if exc else " | ")))
            print(f"{est:15s} {cname:26s} {rows[-1][2]:4s} {rows[-1][3]}", flush=True)
    lines = ["# Scenario Results", "",
             "Generated by `python scripts/run_scenarios.py --large`. Every run must pass validation (S1–S6, "
             "hard policies, format), hold every hard policy, and beat the as-is estate and both sanity anchors.", "",
             "## Estates", "", "| Estate | What it stresses |", "|---|---|"]
    lines += [f"| `{k}` | {d} |" for k, (d, _) in scenarios.ESTATES.items()]
    lines += ["", "## Results", "",
              "| Estate | Configuration | Result | Apps | QMs | Channel pairs | Flow on one QM | TCI | Time | Notes |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for est, cname, res, detail in rows:
        if res == "infeasible":
            lines.append(f"| `{est}` | `{cname}` | infeasible (explained) | | | | | | | {detail} |")
        else:
            lines.append(f"| `{est}` | `{cname}` | {res} | {detail} |")
    lines += ["", f"{len(rows)} runs, {failures} failed.", ""]
    pathlib.Path(a.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"\n{len(rows)} runs, {failures} failed -> {a.out}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
